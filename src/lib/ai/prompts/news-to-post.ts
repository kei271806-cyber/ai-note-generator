export function buildNewsToPostPrompt(
  newsTitle: string,
  newsSummary: string
): string {
  return `あなたはSNS投稿のプロです。以下のAIニュースをThreads投稿に変換してください。

【ルール】
- ニュース転載禁止。「自分の仕事・副業にどう活かせるか」を必ず入れる
- 「これを使うとこんなことができる」「自分ならこう使う」という気づきを与える
- ネガティブな反応（「また覚えることが増える」など）禁止
- 前向きに、でも煽らず。「こんな使い方ができそう」くらいの温度感
- 読者が明日から行動できるヒントや視点を添える
- 150〜200字
- 改行2〜3回
- ニュースの出典不要
- 「〜が発表されました」のような報道体禁止
- 投稿文のみ出力

【ニュースタイトル】
${newsTitle}

【ニュース概要】
${newsSummary}

投稿文のみ出力してください。`
}
